import { parseCidr } from 'cidr-tools';
import { stringifyIp } from 'ip-bigint';
import isCidr from 'is-cidr';

import { removeNewlines, iptablesTemplate } from '#server/utils/template';
import { exec } from '#server/utils/cmd';
import { WG_ENV } from '#server/utils/config';
import type { ClientType } from '#db/repositories/client/types';
import type { InterfaceType } from '#db/repositories/interface/types';
import type { UserConfigType } from '#db/repositories/userConfig/types';
import type { HooksType } from '#db/repositories/hooks/types';

type Options = {
  enableIpv6?: boolean;
};

// needed to support cli
const wgExecutable =
  typeof WG_ENV !== 'undefined' ? WG_ENV.WG_EXECUTABLE : 'dev';

function parseRunningAllowedIps(output: string) {
  const allowedIps = new Set<string>();

  for (const line of output.split('\n')) {
    const separator = line.indexOf('\t');
    if (separator === -1) {
      continue;
    }

    for (const value of line.slice(separator + 1).split(/\s+/)) {
      if (isCidr(value)) {
        allowedIps.add(value);
      }
    }
  }

  return allowedIps;
}

function parseConfigAllowedIps(output: string) {
  const allowedIps = new Set<string>();

  for (const line of output.split('\n')) {
    const match = line.match(/^\s*AllowedIPs\s*=\s*(.+)$/i);
    if (!match) {
      continue;
    }

    for (const value of match[1]!.split(',').map((value) => value.trim())) {
      if (isCidr(value)) {
        allowedIps.add(value);
      }
    }
  }

  return allowedIps;
}

function isDefaultRoute(cidr: string) {
  return parseCidr(cidr).prefix === '0';
}

function routeFamily(cidr: string) {
  return cidr.includes(':') ? '-6' : '-4';
}

async function syncRoutes(
  infName: string,
  routingTable: string,
  previousAllowedIps: Set<string>,
  desiredAllowedIps: Set<string>
) {
  if (routingTable === 'off') {
    return;
  }

  const table = routingTable === 'auto' ? '' : ` table ${routingTable}`;

  for (const cidr of previousAllowedIps.difference(desiredAllowedIps)) {
    if (routingTable === 'auto' && isDefaultRoute(cidr)) {
      continue;
    }

    await exec(
      `ip ${routeFamily(cidr)} route delete ${cidr} dev ${infName}${table} 2>/dev/null || true`
    );
  }

  for (const cidr of desiredAllowedIps) {
    if (routingTable === 'auto' && isDefaultRoute(cidr)) {
      continue;
    }

    if (routingTable !== 'auto') {
      await exec(
        `ip ${routeFamily(cidr)} route replace ${cidr} dev ${infName}${table}`
      );
      continue;
    }

    const existingRoute = await exec(
      `ip ${routeFamily(cidr)} route show dev ${infName} match ${cidr}`
    );
    if (!existingRoute) {
      await exec(`ip ${routeFamily(cidr)} route add ${cidr} dev ${infName}`);
    }
  }
}

export const wg = {
  generateServerPeer: (
    client: Omit<ClientType, 'createdAt' | 'updatedAt'>,
    options: Options = {}
  ) => {
    const { enableIpv6 = true } = options;

    const allowedIps = [
      `${client.ipv4Address}/32`,
      ...(enableIpv6 ? [`${client.ipv6Address}/128`] : []),
      ...(client.serverAllowedIps ?? []),
    ];

    const extraLines = [];
    if (client.serverEndpoint) {
      extraLines.push(`Endpoint = ${client.serverEndpoint}`);
    }

    return `# Client: ${client.name} (${client.id})
[Peer]
PublicKey = ${client.publicKey}
PresharedKey = ${client.preSharedKey}
AllowedIPs = ${allowedIps.join(', ')}${extraLines.length ? `\n${extraLines.join('\n')}` : ''}`;
  },

  generateServerInterface: (
    wgInterface: InterfaceType,
    hooks: HooksType,
    options: Options = {}
  ) => {
    const { enableIpv6 = true } = options;

    const cidr4 = parseCidr(wgInterface.ipv4Cidr);
    const cidr6 = parseCidr(wgInterface.ipv6Cidr);
    const ipv4Addr = stringifyIp({ number: cidr4.start + 1n, version: 4 });
    const ipv6Addr = stringifyIp({ number: cidr6.start + 1n, version: 6 });

    const address =
      `${ipv4Addr}/${cidr4.prefix}` +
      (enableIpv6 ? `, ${ipv6Addr}/${cidr6.prefix}` : '');

    let awgLines: string[] = [];

    if (wgExecutable === 'awg') {
      const parameters = {
        Jc: wgInterface.jC,
        Jmin: wgInterface.jMin,
        Jmax: wgInterface.jMax,
        S1: wgInterface.s1,
        S2: wgInterface.s2,
        S3: wgInterface.s3,
        S4: wgInterface.s4,
        H1: wgInterface.h1,
        H2: wgInterface.h2,
        H3: wgInterface.h3,
        H4: wgInterface.h4,
        I1: wgInterface.i1,
        I2: wgInterface.i2,
        I3: wgInterface.i3,
        I4: wgInterface.i4,
        I5: wgInterface.i5,
      } as const;

      awgLines = Object.entries(parameters)
        .filter(([_, value]) => !!value)
        .map(([key, value]) => `${key} = ${value}`);
    }

    const extraLines = [...awgLines].filter((v) => v !== null);

    return `# Note: Do not edit this file directly.
# Your changes will be overwritten!

# Server
[Interface]
PrivateKey = ${wgInterface.privateKey}
Address = ${address}
ListenPort = ${wgInterface.port}
MTU = ${wgInterface.mtu}
Table = ${wgInterface.routingTable}
${extraLines.length ? `${extraLines.join('\n')}\n` : ''}
PreUp = ${iptablesTemplate(hooks.preUp, wgInterface)}
PostUp = ${iptablesTemplate(hooks.postUp, wgInterface)}
PreDown = ${iptablesTemplate(hooks.preDown, wgInterface)}
PostDown = ${iptablesTemplate(hooks.postDown, wgInterface)}`;
  },

  generateClientConfig: (
    wgInterface: InterfaceType,
    userConfig: UserConfigType,
    client: ClientType,
    options: Options = {}
  ) => {
    const { enableIpv6 = true } = options;

    const address =
      `${client.ipv4Address}/32` +
      (enableIpv6 ? `, ${client.ipv6Address}/128` : '');

    const hookLines = [
      client.preUp ? `PreUp = ${removeNewlines(client.preUp)}` : null,
      client.postUp ? `PostUp = ${removeNewlines(client.postUp)}` : null,
      client.preDown ? `PreDown = ${removeNewlines(client.preDown)}` : null,
      client.postDown ? `PostDown = ${removeNewlines(client.postDown)}` : null,
    ];

    const dnsServers = client.dns ?? userConfig.defaultDns;
    const dnsLine =
      dnsServers.length > 0 ? `DNS = ${dnsServers.join(', ')}` : null;

    let awgLines: string[] = [];

    if (wgExecutable === 'awg') {
      const parameters = {
        Jc: client.jC,
        Jmin: client.jMin,
        Jmax: client.jMax,
        S1: wgInterface.s1,
        S2: wgInterface.s2,
        S3: wgInterface.s3,
        S4: wgInterface.s4,
        H1: wgInterface.h1,
        H2: wgInterface.h2,
        H3: wgInterface.h3,
        H4: wgInterface.h4,
        I1: client.i1,
        I2: client.i2,
        I3: client.i3,
        I4: client.i4,
        I5: client.i5,
      } as const;

      awgLines = Object.entries(parameters)
        .filter(([_, value]) => !!value)
        .map(([key, value]) => `${key} = ${value}`);
    }

    const extraLines = [dnsLine, ...hookLines, ...awgLines].filter(
      (v) => v !== null
    );

    return `[Interface]
PrivateKey = ${client.privateKey}
Address = ${address}
MTU = ${client.mtu}
${extraLines.length ? `${extraLines.join('\n')}\n` : ''}
[Peer]
PublicKey = ${wgInterface.publicKey}
PresharedKey = ${client.preSharedKey}
AllowedIPs = ${(client.allowedIps ?? userConfig.defaultAllowedIps).join(', ')}
PersistentKeepalive = ${client.persistentKeepalive}
Endpoint = ${userConfig.host}:${userConfig.port}`;
  },

  generatePrivateKey: () => {
    return exec(`${wgExecutable} genkey`);
  },

  getPublicKey: (privateKey: string) => {
    return exec(`echo ${privateKey} | ${wgExecutable} pubkey`, {
      log: `echo ***hidden*** | ${wgExecutable} pubkey`,
    });
  },

  generatePreSharedKey: () => {
    return exec(`${wgExecutable} genpsk`);
  },

  up: (infName: string) => {
    return exec(`${wgExecutable}-quick up ${infName}`);
  },

  down: (infName: string) => {
    return exec(`${wgExecutable}-quick down ${infName}`);
  },

  restart: (infName: string) => {
    return exec(
      `${wgExecutable}-quick down ${infName}; ${wgExecutable}-quick up ${infName}`
    );
  },

  sync: async (infName: string, routingTable: string) => {
    const previousAllowedIps = parseRunningAllowedIps(
      await exec(`${wgExecutable} show ${infName} allowed-ips`)
    );
    const desiredAllowedIps = parseConfigAllowedIps(
      await exec(`${wgExecutable}-quick strip ${infName}`)
    );

    const defaultRouteChanged = [
      ...previousAllowedIps.symmetricDifference(desiredAllowedIps),
    ].some((cidr) => isDefaultRoute(cidr));

    // wg-quick installs policy-routing rules for default routes. Recreate the
    // interface when one changes so those rules stay in sync as well.
    if (routingTable === 'auto' && defaultRouteChanged) {
      return exec(
        `${wgExecutable}-quick down ${infName}; ${wgExecutable}-quick up ${infName}`
      );
    }

    await exec(
      `${wgExecutable} syncconf ${infName} <(${wgExecutable}-quick strip ${infName})`
    );
    await syncRoutes(
      infName,
      routingTable,
      previousAllowedIps,
      desiredAllowedIps
    );
  },

  dump: async (infName: string) => {
    const rawDump = await exec(`${wgExecutable} show ${infName} dump`, {
      log: false,
    });

    type wgDumpLine = [
      string,
      string,
      string,
      string,
      string,
      string,
      string,
      string,
    ];

    return rawDump
      .trim()
      .split('\n')
      .slice(1)
      .map((line) => {
        const splitLines = line.split('\t');
        const [
          publicKey,
          preSharedKey,
          endpoint,
          allowedIps,
          latestHandshakeAt,
          transferRx,
          transferTx,
          persistentKeepalive,
        ] = splitLines as wgDumpLine;

        return {
          publicKey,
          preSharedKey,
          endpoint: endpoint === '(none)' ? null : endpoint,
          allowedIps,
          latestHandshakeAt:
            latestHandshakeAt === '0'
              ? null
              : new Date(Number.parseInt(`${latestHandshakeAt}000`)),
          transferRx: Number.parseInt(transferRx),
          transferTx: Number.parseInt(transferTx),
          persistentKeepalive: persistentKeepalive,
        };
      });
  },
};
