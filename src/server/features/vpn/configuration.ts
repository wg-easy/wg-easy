import { normalizeCidr, parseCidr } from 'cidr-tools';

import { zeroWireGuardKey } from '#shared/utils/wireguard';
import { formatEndpoint } from '#server/utils/endpoint';
import { getGatewayAddress } from '#server/utils/ip';
import type { ClientType } from '#db/repositories/client/types';
import type { InterfaceType } from '#db/repositories/interface/types';
import type { UserConfigType } from '#db/repositories/userConfig/types';
import type { HooksType } from '#db/repositories/hooks/types';

type Options = {
  enableIpv6?: boolean;
  amnezia?: boolean;
  uiPort?: string;
};
export type PeerAddresses = {
  ipv4Address: string | null;
  ipv6Address: string | null;
};
export type ServerPeer = Omit<
  ClientType,
  'createdAt' | 'updatedAt' | keyof PeerAddresses
> &
  PeerAddresses;

/** The complete server file, including enabled peers and its final newline. */
export function generateServerConfig(
  network: InterfaceType,
  hooks: HooksType,
  clients: ServerPeer[],
  options: Options = {}
) {
  return [
    generateServerInterface(network, hooks, options),
    ...generateServerPeers(clients, options),
    '',
  ].join('\n\n');
}

/** Only fields understood by wg/awg syncconf belong in the tunnel configuration. */
export function generateTunnelConfig(
  network: InterfaceType,
  clients: ServerPeer[],
  fwmark: string,
  options: Options
) {
  const fields = [
    '[Interface]',
    `PrivateKey = ${network.privateKey}`,
    `ListenPort = ${network.port}`,
    `FwMark = ${fwmark}`,
    ...(options.amnezia ? buildAwgLines(network) : []),
  ];
  return [fields.join('\n'), ...generateServerPeers(clients, options), ''].join(
    '\n\n'
  );
}

function generateServerPeers(clients: ServerPeer[], options: Options) {
  return clients
    .filter((client) => client.enabled)
    .map((client) => generateServerPeer(client, options));
}

export function peerAllowedIps(
  client: Pick<ServerPeer, 'ipv4Address' | 'ipv6Address' | 'serverAllowedIps'>,
  enableIpv6: boolean
) {
  return [
    ...(client.ipv4Address ? [`${client.ipv4Address}/32`] : []),
    ...(enableIpv6 && client.ipv6Address ? [`${client.ipv6Address}/128`] : []),
    ...(client.serverAllowedIps ?? []).filter(
      (prefix) => enableIpv6 || !prefix.includes(':')
    ),
  ];
}

function generateServerPeer(client: ServerPeer, options: Options = {}) {
  const allowedIps = peerAllowedIps(client, options.enableIpv6 ?? true);

  const lines = [
    `# Client: ${client.name} (${client.id})`,
    '[Peer]',
    `PublicKey = ${client.publicKey}`,
    // An all-zero key clears any preshared key on the active peer.
    `PresharedKey = ${client.preSharedKey ?? zeroWireGuardKey}`,
  ];
  if (allowedIps.length) {
    lines.push(`AllowedIPs = ${allowedIps.join(', ')}`);
  }
  if (client.serverEndpoint) {
    lines.push(`Endpoint = ${client.serverEndpoint}`);
  }
  return lines.join('\n');
}

export function tunnelAddresses(network: InterfaceType, enableIpv6: boolean) {
  return [network.ipv4Cidr, ...(enableIpv6 ? [network.ipv6Cidr] : [])].map(
    (value) => {
      const cidr = parseCidr(value);
      return `${getGatewayAddress(cidr)}/${cidr.prefix}`;
    }
  );
}

function generateServerInterface(
  wgInterface: InterfaceType,
  hooks: HooksType,
  options: Options = {}
) {
  const { enableIpv6 = true } = options;

  const address = tunnelAddresses(wgInterface, enableIpv6).join(', ');

  const extraLines = options.amnezia ? buildAwgLines(wgInterface) : [];
  const configHook = (text: string) =>
    removeNewlines(expandHook(text, wgInterface, options.uiPort ?? '51821'));

  return `# Note: Do not edit this file directly.
# Your changes will be overwritten!

# Server
[Interface]
PrivateKey = ${wgInterface.privateKey}
Address = ${address}
ListenPort = ${wgInterface.port}
${wgInterface.mtu !== null ? `MTU = ${wgInterface.mtu}\n` : ''}Table = ${wgInterface.routingTable}
${extraLines.length ? `${extraLines.join('\n')}\n` : ''}
PreUp = ${configHook(hooks.preUp)}
PostUp = ${configHook(hooks.postUp)}
PreDown = ${configHook(hooks.preDown)}
PostDown = ${configHook(hooks.postDown)}`;
}

export function generateClientConfig(
  wgInterface: InterfaceType,
  userConfig: UserConfigType,
  client: ClientType,
  options: Options = {}
) {
  const { enableIpv6 = true } = options;

  const address =
    `${client.ipv4Address}/32` +
    (enableIpv6 ? `, ${client.ipv6Address}/128` : '');

  const hookLines = [
    client.preUp ? `PreUp = ${removeNewlines(client.preUp)}` : null,
    client.postUp ? `PostUp = ${removeNewlines(client.postUp)}` : null,
    client.preDown ? `PreDown = ${removeNewlines(client.preDown)}` : null,
    client.postDown ? `PostDown = ${removeNewlines(client.postDown)}` : null,
  ];

  const dnsServers = client.dns ?? userConfig.defaultDns;
  const dnsLine =
    dnsServers.length > 0 ? `DNS = ${dnsServers.join(', ')}` : null;
  const mtuLine = client.mtu !== null ? `MTU = ${client.mtu}` : null;

  const awgLines = options.amnezia ? buildAwgLines(wgInterface, client) : [];

  const extraLines = [mtuLine, dnsLine, ...hookLines, ...awgLines].filter(
    (v) => v !== null
  );

  const privateKeyLine = client.privateKey
    ? `PrivateKey = ${client.privateKey}`
    : '# Configuration template: on the device, uncomment the next line and enter its private key.\n# PrivateKey = <device private key>';

  return `[Interface]
${privateKeyLine}
Address = ${address}
${extraLines.length ? `${extraLines.join('\n')}\n` : ''}
[Peer]
PublicKey = ${wgInterface.publicKey}
${client.preSharedKey ? `PresharedKey = ${client.preSharedKey}\n` : ''}AllowedIPs = ${(client.allowedIps ?? userConfig.defaultAllowedIps).join(', ')}
PersistentKeepalive = ${client.persistentKeepalive}
Endpoint = ${formatEndpoint(userConfig.host, userConfig.port)}`;
}

/** Shared S/H parameters come from the server; other obfuscation settings belong to each peer. */
function buildAwgLines(network: InterfaceType, client?: ClientType) {
  const own = client ?? network;
  const parameters = {
    Jc: own.jC,
    Jmin: own.jMin,
    Jmax: own.jMax,
    S1: network.s1,
    S2: network.s2,
    S3: network.s3,
    S4: network.s4,
    H1: network.h1,
    H2: network.h2,
    H3: network.h3,
    H4: network.h4,
    I1: own.i1,
    I2: own.i2,
    I3: own.i3,
    I4: own.i4,
    I5: own.i5,
    HeaderProtectionKey: network.headerProtectionKey,
    ContentPaddingAddition: own.contentPaddingAddition,
    RekeyAfterTime: own.rekeyAfterTime,
    RekeyTimeout: own.rekeyTimeout,
    RejectAfterTime: own.rejectAfterTime,
    KeepaliveTimeout: own.keepaliveTimeout,
    MaxHandshakeAttempts: own.maxHandshakeAttempts,
    RandomTrailers: network.randomTrailers,
    DisableCookies: own.disableCookies,
  };
  return Object.entries(parameters)
    .filter(([, value]) => typeof value === 'boolean' || value)
    .map(
      ([key, value]) =>
        `${key} = ${typeof value === 'boolean' ? (value ? 'on' : 'off') : value}`
    );
}

function removeNewlines(text: string) {
  return text.replace(/\r\n|\r|\n/g, ' ');
}

export function expandHook(
  text: string,
  network: InterfaceType,
  uiPort: string
) {
  const values: Record<string, string> = {
    ipv4Cidr: normalizeCidr(network.ipv4Cidr),
    ipv6Cidr: normalizeCidr(network.ipv6Cidr),
    device: network.device,
    interface: network.name,
    port: network.port.toString(),
    uiPort,
  };
  return text
    .replace(/\r\n?/g, '\n')
    .replace(/\{\{(\w+)\}\}/g, (match, key: string) => values[key] ?? match);
}
