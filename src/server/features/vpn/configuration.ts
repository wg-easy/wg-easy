import { parseCidr } from 'cidr-tools';
import { stringifyIp } from 'ip-bigint';

import { formatEndpoint } from '#server/utils/endpoint';
import type { ClientType } from '#db/repositories/client/types';
import type { InterfaceType } from '#db/repositories/interface/types';
import type { UserConfigType } from '#db/repositories/userConfig/types';
import type { HooksType } from '#db/repositories/hooks/types';

type Options = {
  enableIpv6?: boolean;
  amnezia?: boolean;
  uiPort?: string;
};

/** The complete server file, including enabled peers and its final newline. */
export function generateServerConfig(
  network: InterfaceType,
  hooks: HooksType,
  clients: Omit<ClientType, 'createdAt' | 'updatedAt'>[],
  options: Options = {}
) {
  return [
    generateServerInterface(network, hooks, options),
    ...clients
      .filter((client) => client.enabled)
      .map((client) => generateServerPeer(client, options)),
    '',
  ].join('\n\n');
}

// WireGuard uses an all-zero key to explicitly clear the active peer's preshared key.
const unsetPreSharedKey = 'AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=';

function generateServerPeer(
  client: Omit<ClientType, 'createdAt' | 'updatedAt'>,
  options: Options = {}
) {
  const { enableIpv6 = true } = options;

  const allowedIps = [
    `${client.ipv4Address}/32`,
    ...(enableIpv6 ? [`${client.ipv6Address}/128`] : []),
    ...(client.serverAllowedIps ?? []),
  ];

  const extraLines = [];
  if (client.serverEndpoint) {
    extraLines.push(`Endpoint = ${client.serverEndpoint}`);
  }

  return `# Client: ${client.name} (${client.id})
[Peer]
PublicKey = ${client.publicKey}
PresharedKey = ${client.preSharedKey ?? unsetPreSharedKey}
AllowedIPs = ${allowedIps.join(', ')}${extraLines.length ? `\n${extraLines.join('\n')}` : ''}`;
}

function generateServerInterface(
  wgInterface: InterfaceType,
  hooks: HooksType,
  options: Options = {}
) {
  const { enableIpv6 = true } = options;

  const cidr4 = parseCidr(wgInterface.ipv4Cidr);
  const cidr6 = parseCidr(wgInterface.ipv6Cidr);
  const ipv4Addr = stringifyIp({ number: cidr4.start + 1n, version: 4 });
  const ipv6Addr = stringifyIp({ number: cidr6.start + 1n, version: 6 });

  const address =
    `${ipv4Addr}/${cidr4.prefix}` +
    (enableIpv6 ? `, ${ipv6Addr}/${cidr6.prefix}` : '');

  const extraLines = options.amnezia ? buildAwgLines(wgInterface) : [];

  return `# Note: Do not edit this file directly.
# Your changes will be overwritten!

# Server
[Interface]
PrivateKey = ${wgInterface.privateKey}
Address = ${address}
ListenPort = ${wgInterface.port}
${wgInterface.mtu !== null ? `MTU = ${wgInterface.mtu}\n` : ''}Table = ${wgInterface.routingTable}
${extraLines.length ? `${extraLines.join('\n')}\n` : ''}
PreUp = ${iptablesTemplate(hooks.preUp, wgInterface, options.uiPort ?? '51821')}
PostUp = ${iptablesTemplate(hooks.postUp, wgInterface, options.uiPort ?? '51821')}
PreDown = ${iptablesTemplate(hooks.preDown, wgInterface, options.uiPort ?? '51821')}
PostDown = ${iptablesTemplate(hooks.postDown, wgInterface, options.uiPort ?? '51821')}`;
}

export function generateClientConfig(
  wgInterface: InterfaceType,
  userConfig: UserConfigType,
  client: ClientType,
  options: Options = {}
) {
  const { enableIpv6 = true } = options;

  const address =
    `${client.ipv4Address}/32` +
    (enableIpv6 ? `, ${client.ipv6Address}/128` : '');

  const hookLines = [
    client.preUp ? `PreUp = ${removeNewlines(client.preUp)}` : null,
    client.postUp ? `PostUp = ${removeNewlines(client.postUp)}` : null,
    client.preDown ? `PreDown = ${removeNewlines(client.preDown)}` : null,
    client.postDown ? `PostDown = ${removeNewlines(client.postDown)}` : null,
  ];

  const dnsServers = client.dns ?? userConfig.defaultDns;
  const dnsLine =
    dnsServers.length > 0 ? `DNS = ${dnsServers.join(', ')}` : null;
  const mtuLine = client.mtu !== null ? `MTU = ${client.mtu}` : null;

  const awgLines = options.amnezia ? buildAwgLines(wgInterface, client) : [];

  const extraLines = [mtuLine, dnsLine, ...hookLines, ...awgLines].filter(
    (v) => v !== null
  );

  return `[Interface]
PrivateKey = ${client.privateKey}
Address = ${address}
${extraLines.length ? `${extraLines.join('\n')}\n` : ''}
[Peer]
PublicKey = ${wgInterface.publicKey}
${client.preSharedKey ? `PresharedKey = ${client.preSharedKey}\n` : ''}AllowedIPs = ${(client.allowedIps ?? userConfig.defaultAllowedIps).join(', ')}
PersistentKeepalive = ${client.persistentKeepalive}
Endpoint = ${formatEndpoint(userConfig.host, userConfig.port)}`;
}

/** Shared S/H parameters come from the server; other obfuscation settings belong to each peer. */
function buildAwgLines(network: InterfaceType, client?: ClientType) {
  const own = client ?? network;
  const parameters = {
    Jc: own.jC,
    Jmin: own.jMin,
    Jmax: own.jMax,
    S1: network.s1,
    S2: network.s2,
    S3: network.s3,
    S4: network.s4,
    H1: network.h1,
    H2: network.h2,
    H3: network.h3,
    H4: network.h4,
    I1: own.i1,
    I2: own.i2,
    I3: own.i3,
    I4: own.i4,
    I5: own.i5,
    HeaderProtectionKey: network.headerProtectionKey,
    ContentPaddingAddition: own.contentPaddingAddition,
    RekeyAfterTime: own.rekeyAfterTime,
    RekeyTimeout: own.rekeyTimeout,
    RejectAfterTime: own.rejectAfterTime,
    KeepaliveTimeout: own.keepaliveTimeout,
    MaxHandshakeAttempts: own.maxHandshakeAttempts,
    RandomTrailers: network.randomTrailers,
    DisableCookies: own.disableCookies,
  };
  return Object.entries(parameters)
    .filter(([, value]) => typeof value === 'boolean' || value)
    .map(
      ([key, value]) =>
        `${key} = ${typeof value === 'boolean' ? (value ? 'on' : 'off') : value}`
    );
}

function removeNewlines(text: string) {
  return text.replace(/\r\n|\r|\n/g, ' ');
}

function iptablesTemplate(
  text: string,
  network: InterfaceType,
  uiPort: string
) {
  const values: Record<string, string> = {
    ipv4Cidr: network.ipv4Cidr,
    ipv6Cidr: network.ipv6Cidr,
    device: network.device,
    interface: network.name,
    port: network.port.toString(),
    uiPort,
  };
  return removeNewlines(text).replace(
    /\{\{(\w+)\}\}/g,
    (match, key: string) => values[key] ?? match
  );
}
